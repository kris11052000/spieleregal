// Sichere Brücke zwischen Oberfläche und Hauptprozess
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  loadDb: () => ipcRenderer.invoke('db:load'),
  saveDb: (data) => ipcRenderer.invoke('db:save', data),
  appInfo: () => ipcRenderer.invoke('app:info'),
  openDataFolder: () => ipcRenderer.invoke('app:openDataFolder'),
  coverFromDataUrl: (dataUrl, opts) => ipcRenderer.invoke('cover:fromDataUrl', dataUrl, opts),
  coverProduct: (name) => ipcRenderer.invoke('cover:product', name),
  chooseCover: (opts) => ipcRenderer.invoke('cover:choose', opts),
  deleteCover: (name) => ipcRenderer.invoke('cover:delete', name),
  coverUrl: (name) => (name ? 'cover://img/' + encodeURIComponent(name) : ''),
  labelsPdf: (html, layout, name) => ipcRenderer.invoke('labels:pdf', { html, layout, name }),
  labelsPrint: (html, layout) => ipcRenderer.invoke('labels:print', { html, layout }),
  exportBackup: (data) => ipcRenderer.invoke('backup:export', data),
  importBackup: () => ipcRenderer.invoke('backup:import'),
  openExternal: (url) => ipcRenderer.invoke('shell:openExternal', url),
  onMenu: (fn) => ipcRenderer.on('menu', (_e, cmd) => fn(cmd)),
  igdbGetConfig: () => ipcRenderer.invoke('igdb:getConfig'),
  igdbSetConfig: (cfg) => ipcRenderer.invoke('igdb:setConfig', cfg),
  igdbTest: () => ipcRenderer.invoke('igdb:test'),
  igdbSearchGames: (q) => ipcRenderer.invoke('igdb:searchGames', q),
  igdbSearchPlatforms: (q) => ipcRenderer.invoke('igdb:searchPlatforms', q),
  igdbReleases: (opts) => ipcRenderer.invoke('igdb:releases', opts),
  coverFromUrl: (url, opts) => ipcRenderer.invoke('cover:fromUrl', url, opts),
  accountsStatus: () => ipcRenderer.invoke('accounts:status'),
  psnConnect: (npsso) => ipcRenderer.invoke('psn:connect', npsso),
  psnDisconnect: () => ipcRenderer.invoke('psn:disconnect'),
  psnTitles: () => ipcRenderer.invoke('psn:titles'),
  psnTrophies: (id, service) => ipcRenderer.invoke('psn:trophies', id, service),
  xboxConnect: (key) => ipcRenderer.invoke('xbox:connect', key),
  xboxDisconnect: () => ipcRenderer.invoke('xbox:disconnect'),
  xboxTitles: () => ipcRenderer.invoke('xbox:titles'),
  xboxTrophies: (id) => ipcRenderer.invoke('xbox:trophies', id),
  ebaySetConfig: (cfg) => ipcRenderer.invoke('ebay:setConfig', cfg),
  ebayTest: () => ipcRenderer.invoke('ebay:test'),
  ebayEstimate: (q) => ipcRenderer.invoke('ebay:estimate', q),
  commonsSearch: (q) => ipcRenderer.invoke('commons:search', q),
  wikiImage: (names) => ipcRenderer.invoke('wiki:image', names),
  webFetch: (url) => ipcRenderer.invoke('web:fetch', url),
  platform: process.platform,
  hasNativeMenu: true
});
